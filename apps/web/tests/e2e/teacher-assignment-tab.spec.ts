import { expect, test } from "@playwright/test";
test("teacher creates and assigns homework to class",async({page})=>{
  await page.goto("/teacher/classes/if-2609/assignments");
  await page.getByRole("button",{name:"Tạo bài"}).click();
  await expect(page.getByText("Tạo bài tập cho lớp",{exact:true})).toBeVisible();
  await page.getByLabel("Tên bài").fill("Homework Unit 5");
  await page.getByLabel("Hạn nộp").fill("30/08/2026 · 21:00");
  await page.getByRole("button",{name:"Lưu bản nháp"}).last().click();
  await expect(page.getByText("Đã tạo bản nháp",{exact:false})).toBeVisible();
  await expect(page.getByRole("button", { name: /Homework Unit 5/ }).first()).toBeVisible();
  await page.getByRole("button",{name:"Công bố"}).last().click();
  await expect(page.getByText("Giao bài cho lớp",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Giao bài"}).click();
  await expect(page.getByText("Đã giao bài cho lớp",{exact:false})).toBeVisible();
  await page.getByRole("button", { name: "Chỉnh sửa" }).last().click();
  await expect(page.getByText("Chỉnh sửa bài tập", { exact: true })).toBeVisible();
  await page.getByLabel("Tên bài").fill("Homework Unit 5 - Updated");
  await page.getByRole("button", { name: "Lưu thay đổi" }).click();
  await expect(page.getByText("Homework Unit 5 - Updated", { exact: true })).toBeVisible();
  const writingRow = page.locator("tr").filter({ hasText: "Writing Task 1" }).first();
  await writingRow.getByRole("button", { name: "Xem" }).click();
  await expect(page.getByText("Chấm bài · Writing Task 1", { exact: true })).toBeVisible();
});
